"""Analyse the paraphrase hold-out (backend/reports/holdout_paraphrase).

The set exists to separate two things the frame hold-out confounds: unfamiliar sentence structure and unfamiliar
vocabulary. Every utterance was written for a target attribute triple by an external model, so each row carries flags
saying whether the wording for its named attributes comes from the policy's own catalogue. Accuracy split by those
flags measures directly how much of the model's competence is lexical.

Metric is exact-tuple match, as everywhere else. Rows are clustered by attribute cell (each cell's utterances were
generated in one call), so intervals come from a cluster bootstrap over seeds then cells then rows.
Writes tables/T16_paraphrase_holdout.csv and backend/reports/holdout_paraphrase/analysis.{json,md}.
"""
from __future__ import annotations
import csv, json, re, statistics as st, sys
from collections import defaultdict, Counter
from pathlib import Path
import numpy as np
REPO = Path(__file__).resolve().parents[1]; R = REPO / "backend/reports/holdout_paraphrase"; TAB = REPO.parent / "tables"
sys.path.insert(0, str(REPO / "backend")); sys.path.insert(0, str(REPO / "backend/models"))
from compact_llm import training_data as td
DIMS = ("H", "S", "B", "Dimmer", "CT")
DATA = REPO / "backend/models/compact_llm/datasets/holdout_paraphrase/K240/holdout_paraphrase.jsonl"
NAMES = {"selected_V4k_L8": "selected: d 384, L 8, 4k natural tokenizer (15.7 M)",
         "deployed_W384_L8_V24k": "deployed architecture: d 384, L 8, 24k tokenizer (23.4 M)",
         "X320_V4k": "d 320, L 8, 4k natural tokenizer (11.2 M)",
         "selected_V4k_L8_mixed4": "selected, mixed 4/6/8-bit export (17.1 MB)"}
meta = {json.loads(l)["input"]: json.loads(l) for l in DATA.open(encoding="utf-8")}
inv = {}
for c in [None] + list(td.COLOR_PROFILES):
    for e in [None] + list(td.EMOTION_PROFILES):
        for i in td.INTENSITY_MODIFIERS:
            t = td.normalize_output(td.resolve_case_output({"base_color": c, "emotion": e, "intensity": i})); inv[tuple(int(t[k]) for k in DIMS)] = (c, e, i)
def key(o): return tuple(int(o[k]) for k in DIMS) if o else None
runs = defaultdict(dict)
for f in sorted((R / "per_row").glob("*.jsonl")):
    m = re.match(r"^(.*?)_s(\d+)$", f.stem)
    rows = [json.loads(l) for l in f.open(encoding="utf-8")]
    if len(rows) < len(meta): print(f"  [skip] {f.stem}: {len(rows)}/{len(meta)} rows"); continue
    runs[m.group(1)][int(m.group(2))] = rows
def correct(rows): return [key(r.get("predicted")) == key(r["reference"]) for r in rows]
def exact(rows): return 100 * float(np.mean(correct(rows)))
def cell_of(r): 
    m = meta[r["input"]]; return (m["base_color"], m["emotion"], m["intensity"])
def boot(seed_rows, B=2000, rng=None):
    rng = rng or np.random.default_rng(20260913)
    idx = {}
    for s, rows in seed_rows.items():
        g = defaultdict(list)
        for r, c in zip(rows, correct(rows)): g[cell_of(r)].append(c)
        idx[s] = {k: np.array(v) for k, v in g.items()}
    seeds = list(idx); out = []
    for _ in range(B):
        vals = []
        for s in rng.choice(seeds, len(seeds), replace=True):
            cells = list(idx[s]); drawn = rng.choice(len(cells), len(cells), replace=True)
            pool = [idx[s][cells[j]][rng.integers(0, len(idx[s][cells[j]]), len(idx[s][cells[j]]))] for j in drawn]
            vals.append(np.concatenate(pool).mean())
        out.append(np.mean(vals))
    q = np.percentile(out, [5, 95]); return 100 * float(np.mean(out)), 100 * float(q[0]), 100 * float(q[1])
def tci(d, conf=0.90):
    from scipy import stats
    n = len(d); m = st.mean(d); se = st.stdev(d) / n ** 0.5; t = stats.t.ppf(1 - (1 - conf) / 2, n - 1)
    return m, m - t * se, m + t * se
def group(rows, fn):
    g = defaultdict(list)
    for r, c in zip(rows, correct(rows)): g[fn(meta[r["input"]])].append(c)
    return {k: 100 * float(np.mean(v)) for k, v in g.items()}
def lenbucket(m):
    n = m.get("char_len", len(m["input"]))
    return "≤25" if n <= 25 else "26–45" if n <= 45 else "46–65" if n <= 65 else "≥66"
def lexclass(m):
    L = m["lexical"]
    if L.get("all_named_attributes_use_catalogue_wording"): return "all catalogue wording"
    if L.get("no_named_attribute_uses_catalogue_wording"): return "no catalogue wording"
    return "partial catalogue wording"
out = {"n_rows": len(meta), "configs": {}, "paired": {}}
md = ["# Paraphrase hold-out — analysis", "", f"{len(meta)} utterances generated by an external model for the 240 attribute cells; runs: " +
      ", ".join(f"{c}x{len(s)}" for c, s in sorted(runs.items())) + ".", "",
      "| configuration | seeds | exact % (mean ± SD) | cluster bootstrap 90 % CI | all catalogue wording | partial | no catalogue wording | coarse % | valid output % |",
      "|---|--:|--:|--:|--:|--:|--:|--:|--:|"]
T16 = [["configuration", "seeds", "paraphrase hold-out exact % (mean ± SD)", "90 % CI (cluster bootstrap)", "rows using catalogue wording for every named attribute", "partial", "rows using catalogue wording for none", "coarse %", "valid output %"]]
for cfg in ("selected_V4k_L8", "deployed_W384_L8_V24k", "X320_V4k", "selected_V4k_L8_mixed4"):
    if cfg not in runs: continue
    seeds = sorted(runs[cfg]); accs = [exact(runs[cfg][s]) for s in seeds]; m, sd = st.mean(accs), (st.stdev(accs) if len(accs) > 1 else float("nan"))
    bm, lo, hi = boot(runs[cfg])
    lex = defaultdict(list); ln = defaultdict(list); src = defaultdict(list)
    for s in seeds:
        for k, v in group(runs[cfg][s], lexclass).items(): lex[k].append(v)
        for k, v in group(runs[cfg][s], lenbucket).items(): ln[k].append(v)
        for k, v in group(runs[cfg][s], lambda mm: mm["source"].replace("paraphrase_", "")).items(): src[k].append(v)
    coarse = st.mean(100 * float(np.mean([bool(r.get("coarse")) for r in runs[cfg][s]])) for s in seeds)
    valid = st.mean(100 * float(np.mean([bool(r.get("success")) for r in runs[cfg][s]])) for s in seeds)
    ae = Counter()
    for s in seeds:
        c = Counter(); nw = 0
        for r in runs[cfg][s]:
            p, g = key(r.get("predicted")), key(r["reference"])
            if p == g: continue
            nw += 1
            if p not in inv: c["not_a_policy_tuple"] += 1; continue
            pc, gc = inv[p], inv[g]
            c["colour_wrong"] += pc[0] != gc[0]; c["emotion_wrong"] += pc[1] != gc[1]; c["intensity_wrong"] += pc[2] != gc[2]
        for k2, v in c.items(): ae[k2] += 100 * v / max(nw, 1) / len(seeds)
    L = {k: st.mean(v) for k, v in lex.items()}
    out["configs"][cfg] = {"name": NAMES[cfg], "seeds": seeds, "acc": accs, "mean": m, "sd": sd, "boot_ci90": [lo, hi],
                           "by_lexical": L, "by_length": {k: st.mean(v) for k, v in ln.items()}, "by_source": {k: st.mean(v) for k, v in src.items()},
                           "coarse": coarse, "valid_pct": valid, "attr_err_pct_of_wrong": dict(ae)}
    row = [NAMES[cfg], str(len(seeds)), f"{m:.1f} ± {sd:.1f}", f"[{lo:.1f}, {hi:.1f}]",
           f"{L.get('all catalogue wording', float('nan')):.1f}", f"{L.get('partial catalogue wording', float('nan')):.1f}",
           f"{L.get('no catalogue wording', float('nan')):.1f}", f"{coarse:.1f}", f"{valid:.1f}"]
    T16.append(row); md.append("| " + " | ".join(row) + " |")
    md.append(f"  - by utterance length: " + ", ".join(f"{k} {v:.1f}" for k, v in sorted(out['configs'][cfg]['by_length'].items())))
    md.append(f"  - by source: " + ", ".join(f"{k} {v:.1f}" for k, v in sorted(out['configs'][cfg]['by_source'].items())))
    md.append(f"  - attribute errors, % of wrong rows: colour {ae['colour_wrong']:.1f}, emotion {ae['emotion_wrong']:.1f}, intensity {ae['intensity_wrong']:.1f}, not a policy tuple {ae['not_a_policy_tuple']:.1f}")
if "selected_V4k_L8" in runs and "deployed_W384_L8_V24k" in runs:
    common = sorted(set(runs["selected_V4k_L8"]) & set(runs["deployed_W384_L8_V24k"]))
    d = [exact(runs["selected_V4k_L8"][s]) - exact(runs["deployed_W384_L8_V24k"][s]) for s in common]
    mm, lo, hi = tci(d)
    out["paired"] = {"seeds": common, "d": d, "mean": mm, "ci90": [lo, hi], "favouring_selected": sum(x > 0 for x in d)}
    md += ["", f"Paired selected − deployed: {', '.join(f'{x:+.1f}' for x in d)} pp; mean {mm:+.1f}, 90 % t CI [{lo:+.1f}, {hi:+.1f}]; {sum(x>0 for x in d)}/{len(d)} seeds favour the selected model."]
# lexical class x length cross-tab: is the lexical effect just a length effect?
cross = defaultdict(lambda: defaultdict(list))
if "selected_V4k_L8" in runs:
    for s_ in sorted(runs["selected_V4k_L8"]):
        for r, c in zip(runs["selected_V4k_L8"][s_], correct(runs["selected_V4k_L8"][s_])):
            mm = meta[r["input"]]; cross[lexclass(mm)][lenbucket(mm)].append(c)
    md += ["", "## Is the lexical effect a length effect? (selected model, exact %, n in brackets)", "",
           "| lexical class | ≤25 | 26–45 | 46–65 | ≥66 |", "|---|--:|--:|--:|--:|"]
    for lc in ("all catalogue wording", "partial catalogue wording", "no catalogue wording"):
        cells = []
        for b in ("≤25", "26–45", "46–65", "≥66"):
            v = cross[lc][b]; cells.append(f"{100*float(np.mean(v)):.1f} ({len(v)//len(runs['selected_V4k_L8'])})" if v else "—")
        md.append(f"| {lc} | " + " | ".join(cells) + " |")
    out["lexical_by_length"] = {lc: {b: (100 * float(np.mean(cross[lc][b])) if cross[lc][b] else None) for b in ("≤25", "26–45", "46–65", "≥66")} for lc in cross}
    md.append("")
    md.append("Length buckets in characters. Counts are rows per seed.")
lexn = Counter(lexclass(m) for m in meta.values())
md += ["", "Row composition by lexical novelty: " + ", ".join(f"{k} {v}" for k, v in sorted(lexn.items())) + "."]
out["composition"] = dict(lexn)
with (TAB / "T16_paraphrase_holdout.csv").open("w", newline="", encoding="utf-8") as f: csv.writer(f).writerows(T16)
json.dump(out, (R / "analysis.json").open("w"), indent=1, ensure_ascii=False)
(R / "analysis.md").write_text("\n".join(md) + "\n", encoding="utf-8"); print("\n".join(md))
